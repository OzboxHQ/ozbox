// Markdown (docs/*.md) -> MDX conversion for the docs site. Pure functions; no file access except existsSync
// (to decide whether a repo-relative link points at a file or a directory).
import { existsSync, statSync } from 'node:fs';
import { posix, join } from 'node:path';

export const GENERATED_MARK = '{/* GENERATED by docs-site/scripts/build-site.mjs from';

/** Remove HTML comments outside fenced code (MDX has no syntax for them). */
export function removeHtmlComments(text) {
  const lines = text.split('\n');
  let fence = null;
  let inComment = false;
  const out = [];
  for (let line of lines) {
    if (!inComment) {
      const f = /^\s*(`{3,}|~{3,})/.exec(line);
      if (fence) {
        if (f && f[1][0] === fence[0] && f[1].length >= fence.length) fence = null;
        out.push(line);
        continue;
      }
      if (f) { fence = f[1]; out.push(line); continue; }
    }
    let result = '';
    while (line.length) {
      if (inComment) {
        const end = line.indexOf('-->');
        if (end < 0) { line = ''; break; }
        line = line.slice(end + 3);
        inComment = false;
      } else {
        const start = line.indexOf('<!--');
        if (start < 0) { result += line; line = ''; break; }
        result += line.slice(0, start);
        line = line.slice(start + 4);
        inComment = true;
      }
    }
    out.push(result);
  }
  return out.join('\n');
}

const plain = (s) =>
  s
    .replace(/!?\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/[`*_~]/g, '')
    .replace(/<[^>]+>/g, '')
    .replace(/\\([{}<>])/g, '$1')
    .replace(/\s+/g, ' ')
    .trim();

function firstParagraph(lines) {
  let i = 0;
  while (i < lines.length) {
    const l = lines[i];
    if (l.trim() === '' || /^(#|>|\||---|\*\*\*|```|~~~|[-*+]\s|\d+\.\s|\s{4})/.test(l)) {
      if (/^```|^~~~/.test(l)) break;
      i += 1;
      continue;
    }
    const para = [];
    while (i < lines.length && lines[i].trim() !== '' && !/^(#|```|~~~)/.test(lines[i])) para.push(lines[i++]);
    return para.join(' ');
  }
  return '';
}

function shorten(text, max = 200) {
  if (text.length <= max) return text;
  const cut = text.slice(0, max);
  const sentence = cut.lastIndexOf('. ');
  if (sentence > 60) return cut.slice(0, sentence + 1);
  const word = cut.lastIndexOf(' ');
  return `${cut.slice(0, word > 0 ? word : max)}…`;
}

/**
 * Convert one Markdown source to MDX.
 * ctx: { sourcePath (repo-relative, posix), linkMap (Map repoPath -> site path without leading slash),
 *        repoRoot (absolute), repoUrl }
 */
export function convertMarkdown(source, ctx) {
  const text = removeHtmlComments(source.replace(/\r\n/g, '\n'));
  const lines = text.split('\n');

  let title = '';
  let h1 = -1;
  let fence = null;
  for (let i = 0; i < lines.length; i += 1) {
    const f = /^\s*(`{3,}|~{3,})/.exec(lines[i]);
    if (fence) { if (f && f[1][0] === fence[0] && f[1].length >= fence.length) fence = null; continue; }
    if (f) { fence = f[1]; continue; }
    const m = /^#\s+(.+?)\s*#*\s*$/.exec(lines[i]);
    if (m) { title = plain(m[1]); h1 = i; break; }
  }
  if (!title) throw new Error(`${ctx.sourcePath}: no top-level heading to use as the page title`);

  const afterH1 = lines.slice(h1 + 1);
  const description = shorten(plain(firstParagraph(afterH1))) || title;

  const body = [];
  fence = null;
  for (let i = 0; i < lines.length; i += 1) {
    if (i === h1) continue;
    const line = lines[i];
    const f = /^\s*(`{3,}|~{3,})/.exec(line);
    if (fence) {
      if (f && f[1][0] === fence[0] && f[1].length >= fence.length) fence = null;
      body.push(line);
      continue;
    }
    if (f) { fence = f[1]; body.push(line); continue; }
    body.push(convertLine(line, ctx));
  }

  while (body.length && body[0].trim() === '') body.shift();
  const out = [
    '---',
    `title: ${JSON.stringify(title)}`,
    `description: ${JSON.stringify(description)}`,
    '---',
    '',
    `${GENERATED_MARK} ${ctx.sourcePath}. Do not edit; edit the source and run \`npm run build\` in docs-site. */}`,
    '',
    body.join('\n').replace(/\n{3,}/g, '\n\n').replace(/\s+$/, ''),
    '',
  ];
  return out.join('\n');
}

function convertLine(line, ctx) {
  // split into code spans (kept verbatim) and text
  const parts = [];
  let last = 0;
  for (const m of line.matchAll(/(`+)(?:(?!\1)[\s\S])+?\1/g)) {
    parts.push({ code: false, s: line.slice(last, m.index) });
    parts.push({ code: true, s: m[0] });
    last = m.index + m[0].length;
  }
  parts.push({ code: false, s: line.slice(last) });
  return parts.map((p) => (p.code ? p.s : convertText(p.s, ctx))).join('');
}

function convertText(s, ctx) {
  s = s.replace(/<(https?:\/\/[^>\s]+)>/g, '[$1]($1)');
  s = s.replace(/(?<!\\)\{/g, '\\{').replace(/(?<!\\)\}/g, '\\}');
  s = s.replace(/<(?=[A-Za-z/!?])/g, '&lt;');
  s = s.replace(/\]\(\s*([^)\s]+)((?:\s+"[^"]*")?)\s*\)/g, (_m, target, titlePart) => `](${rewriteLink(target, ctx)}${titlePart})`);
  return s;
}

export function rewriteLink(target, ctx) {
  if (/^([a-z][a-z0-9+.-]*:|\/\/|#)/i.test(target)) return target;
  const i = target.indexOf('#');
  const pathPart = i < 0 ? target : target.slice(0, i);
  const anchor = i < 0 ? '' : target.slice(i);
  if (pathPart === '') return target;
  const resolved = posix.normalize(posix.join(posix.dirname(ctx.sourcePath), pathPart)).replace(/\/$/, '');
  if (resolved.startsWith('..')) throw new Error(`${ctx.sourcePath}: link ${target} leaves the repository`);
  if (ctx.linkMap.has(resolved)) {
    const site = ctx.linkMap.get(resolved);
    return `/${site.replace(/\/index$/, '').replace(/^index$/, '')}${anchor}`.replace(/^\/$/, '/');
  }
  const abs = join(ctx.repoRoot, resolved);
  if (!existsSync(abs)) throw new Error(`${ctx.sourcePath}: link ${target} points at ${resolved}, which does not exist`);
  const kind = statSync(abs).isDirectory() ? 'tree' : 'blob';
  return `${ctx.repoUrl}/${kind}/main/${resolved}${anchor}`;
}
