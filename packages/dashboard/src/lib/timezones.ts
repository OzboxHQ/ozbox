function formatLabel(tz: string): string {
  if (tz === "UTC") return "UTC — Coordinated Universal Time"
  const abbr = TZ_ABBREVIATIONS[tz]
  return tz.replace(/_/g, " ") + (abbr ? ` (${abbr})` : "")
}

