#!/usr/bin/env node
// Render the Homebrew formula (Formula/ozbox.rb) for one release from its `ozbox-cli-manifest.json`.
//
//   node scripts/release/gen-homebrew-formula.mjs <manifest.json> [--repo OWNER/NAME] [--out FILE]
//
// The manifest is the one the release workflow signed; publish-homebrew.yml verifies its signature (cosign) before it
// calls this, so the sha256 values written here are the verified ones. Pre-release versions (with a `-` suffix) are
// refused: a tap carries stable releases only. Prints the formula to stdout when no --out is given.
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

const SHA = /^[0-9a-f]{64}$/;
const VERSION = /^[0-9]+\.[0-9]+(\.[0-9]+)?$/;
const REPO = /^[A-Za-z0-9._-]+\/[A-Za-z0-9._-]+$/;

/** The four programs a formula needs: [os, arch] in the order the formula lists them. */
export const TARGETS = [
  ["darwin", "aarch64"],
  ["darwin", "x86_64"],
  ["linux", "aarch64"],
  ["linux", "x86_64"],
];

export function renderFormula(manifest, repo = "OzboxHQ/ozbox") {
  if (!REPO.test(repo)) throw new Error(`not an owner/name repository: ${repo}`);
  const version = manifest?.version;
  if (typeof version !== "string" || !VERSION.test(version)) {
    throw new Error(`the manifest version is not a stable release version: ${JSON.stringify(version)}`);
  }
  if (!Array.isArray(manifest.binaries)) throw new Error("the manifest lists no programs");
  const pick = (os, arch) => {
    const asset = `ozbox-${os}-${arch}`;
    const e = manifest.binaries.find((b) => b && b.asset === asset && b.arch === arch);
    if (!e) throw new Error(`the manifest has no program for ${os}/${arch} (${asset})`);
    if (typeof e.sha256 !== "string" || !SHA.test(e.sha256)) throw new Error(`the sha256 for ${asset} is not valid`);
    if (e.os !== undefined && e.os !== os) throw new Error(`the manifest entry for ${asset} names another system`);
    return { asset, sha256: e.sha256 };
  };
  const url = (asset) => `https://github.com/${repo}/releases/download/v${version}/${asset}`;
  const block = (os, arch, cpu) => {
    const t = pick(os, arch);
    return `    on_${cpu} do
      url "${url(t.asset)}"
      sha256 "${t.sha256}"
    end`;
  };
  return `# Generated by scripts/release/gen-homebrew-formula.mjs from the signed manifest of release v${version}. Do not edit by hand.
class Ozbox < Formula
  desc "Command line for Oz Box, open-source cloud workstations for AI coding agents"
  homepage "https://github.com/${repo}"
  version "${version}"
  license "Apache-2.0"

  on_macos do
${block("darwin", "aarch64", "arm")}
${block("darwin", "x86_64", "intel")}
  end

  on_linux do
${block("linux", "aarch64", "arm")}
${block("linux", "x86_64", "intel")}
  end

  def install
    # the download is one program file, staged under its release file name (ozbox-<os>-<arch>)
    bin.install Dir["ozbox-*"].first => "ozbox"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/ozbox --version")
  end
end
`;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const args = process.argv.slice(2);
  let file = "";
  let repo = "OzboxHQ/ozbox";
  let out = "";
  for (let i = 0; i < args.length; i++) {
    if (args[i] === "--repo") repo = args[++i] ?? "";
    else if (args[i] === "--out") out = args[++i] ?? "";
    else if (!file) file = args[i];
    else throw new Error(`unexpected argument: ${args[i]}`);
  }
  if (!file) {
    console.error("usage: gen-homebrew-formula.mjs <manifest.json> [--repo OWNER/NAME] [--out FILE]");
    process.exit(2);
  }
  try {
    const text = renderFormula(JSON.parse(readFileSync(file, "utf8")), repo);
    if (out) writeFileSync(out, text);
    else process.stdout.write(text);
  } catch (e) {
    console.error(`gen-homebrew-formula: ${e.message}`);
    process.exit(1);
  }
}
