#!/usr/bin/env python3
"""Generate the table of characters a skill may not contain, from the Unicode Character Database.

    scripts/gen-skill-hidden-chars.py <dir with UnicodeData.txt and DerivedCoreProperties.txt>

Writes crates/ozbox-core/src/skill_hidden.rs and packages/dashboard/src/lib/skill-hidden.ts: the same ranges, so the
server, the box daemon and the page refuse exactly the same characters. A person must be able to see what an agent will read,
so the set is everything that renders as nothing or changes how text reads:

  - General_Category Cc (except tab, line feed, carriage return), Cf, Co, Cn, Zl, Zp
    (Cn is every unassigned code point and noncharacter, so a character newer than the table is refused until it is
    regenerated, never allowed by accident);
  - every Default_Ignorable_Code_Point (variation selectors including U+E0100..U+E01EF, Hangul fillers, the combining grapheme
    joiner, tag characters, interlinear annotation, and more);
  - U+2800 (braille blank), which renders as an empty cell.
"""
import re
import sys
from pathlib import Path

d = Path(sys.argv[1])
ranges = []  # (lo, hi)
assigned = []  # (lo, hi) of every assigned code point
first = None
for line in (d / "UnicodeData.txt").read_text().splitlines():
    f = line.split(";")
    cp, name, gc = int(f[0], 16), f[1], f[2]
    if name.endswith(", First>"):
        first = cp
        continue
    lo = first if name.endswith(", Last>") and first is not None else cp
    first = None
    assigned.append((lo, cp))
    if gc in ("Cf", "Co", "Zl", "Zp") or (gc == "Cc" and cp not in (9, 10, 13)):
        ranges.append((lo, cp))
# Cn: the gaps in the assigned set, up to U+10FFFF
prev = 0
for lo, hi in sorted(assigned):
    if lo > prev:
        ranges.append((prev, lo - 1))
    prev = hi + 1
if prev <= 0x10FFFF:
    ranges.append((prev, 0x10FFFF))
version = ""
in_di = False
for line in (d / "DerivedCoreProperties.txt").read_text().splitlines():
    m = re.match(r"# DerivedCoreProperties-(\S+)\.txt", line)
    if m:
        version = m.group(1)
    m = re.match(r"([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*Default_Ignorable_Code_Point\b", line)
    if m:
        lo = int(m.group(1), 16)
        ranges.append((lo, int(m.group(2) or m.group(1), 16)))
ranges.append((0x2800, 0x2800))
ranges.sort()
merged = []
for lo, hi in ranges:
    if merged and lo <= merged[-1][1] + 1:
        merged[-1] = (merged[-1][0], max(merged[-1][1], hi))
    else:
        merged.append((lo, hi))
for allowed in (9, 10, 13):
    assert not any(lo <= allowed <= hi for lo, hi in merged), allowed
root = Path(__file__).resolve().parent.parent
rust = [
    "// @generated by scripts/gen-skill-hidden-chars.py from the Unicode Character Database "
    f"{version}. Do not edit.",
    "//! The characters a skill may not contain (see `skill_pack::hidden`): inclusive code point ranges, sorted.",
    "",
    f'pub const UNICODE_VERSION: &str = "{version}";',
    "",
    "pub const HIDDEN: &[(u32, u32)] = &[",
]
rust += [f"    (0x{lo:X}, 0x{hi:X})," for lo, hi in merged]
rust += ["];", ""]
(root / "crates/ozbox-core/src/skill_hidden.rs").write_text("\n".join(rust))
ts = [
    f"// @generated by scripts/gen-skill-hidden-chars.py from the Unicode Character Database {version}. Do not edit.",
    "// The characters a skill may not contain: inclusive code point ranges, sorted. The server and the box daemon use the same table.",
    f"export const UNICODE_VERSION = '{version}';",
    "export const HIDDEN_RANGES: readonly (readonly [number, number])[] = [",
]
ts += [f"  [0x{lo:X}, 0x{hi:X}]," for lo, hi in merged]
ts += ["];", ""]
(root / "packages/dashboard/src/lib/skill-hidden.ts").write_text("\n".join(ts))
print(len(merged), "ranges, Unicode", version)
